# ═══════════════════════════════════════════════════════
# ENTRENAMIENTO DE MODELOS COMPARATIVOS
# ═══════════════════════════════════════════════════════

# Seleccionar features
features = ['disconnection_rate', 'total_connections', 'total_disconnections',
            'unique_clients', 'total_auth', 'hour', 'day_of_week', 'is_peak_hour',
            'is_weekend', 'connection_efficiency', 'auth_per_client', 'social_weight']

X = df_ml[features].fillna(0)
y = df_ml['target_critical']

# Split estratificado
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y
)

# Escalar para modelos sensibles
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# Diccionario de modelos a comparar
models = {
    'Random Forest': RandomForestClassifier(n_estimators=100, max_depth=8,
                                           class_weight='balanced', random_state=42),
    'Gradient Boosting': GradientBoostingClassifier(n_estimators=100, max_depth=5, random_state=42),
    'Logistic Regression': LogisticRegression(class_weight='balanced', max_iter=1000, random_state=42)
}

results = {}
print("Entrenando modelos...\n")

for name, model in models.items():
    # Usar datos escalados solo para LR
    X_tr = X_train_scaled if name == 'Logistic Regression' else X_train
    X_te = X_test_scaled if name == 'Logistic Regression' else X_test

    model.fit(X_tr, y_train)
    y_pred = model.predict(X_te)
    y_proba = model.predict_proba(X_te)[:,1]

    results[name] = {
        'model': model,
        'auc': roc_auc_score(y_test, y_proba),
        'accuracy': (y_pred == y_test).mean(),
        'report': classification_report(y_test, y_pred, output_dict=True),
        'y_proba': y_proba,
        'y_pred': y_pred
    }

    print(f"{name}:")
    print(f"   • AUC-ROC: {results[name]['auc']:.3f}")
    print(f"   • Accuracy: {results[name]['accuracy']:.3f}")
    print(f"   • F1-Score (clase crítica): {results[name]['report']['1']['f1-score']:.3f}\n")

# ═══════════════════════════════════════════════════════
