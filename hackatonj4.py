# Extraer zona del nombre del AP
aps['zona'] = aps['ap_name'].str.extract(r'_(.+?)_AP', expand=False)
aps['zona'] = aps['zona'].fillna('Desconocida')

# Ponderación social por zona (ejemplo basado en contexto de Cali)
# En producción: cruzar con datos del DANE, estratificación, ubicación de colegios
SOCIAL_WEIGHT = {
    'Hormiguero': 1.5, 'El Saladito': 1.5, 'Felidia': 1.3, 'La Leonera': 1.3,
    'Pichinde': 1.4, 'Navarro': 1.2, 'La Elvira': 1.1, 'Montebello': 1.0,
    'Los Andes': 1.0, 'La Castilla': 1.1, 'Desconocida': 1.0
}

aps['social_weight'] = aps['zona'].map(lambda x: SOCIAL_WEIGHT.get(x, 1.0))

# Unir métricas con información de APs
df_ml = metrics.merge(aps[['ap_name', 'status', 'zona', 'social_weight']], on='ap_name', how='left')

# Crear features temporales
df_ml['hour'] = df_ml['timestamp_hour'].dt.hour
df_ml['day_of_week'] = df_ml['timestamp_hour'].dt.dayofweek
df_ml['is_peak_hour'] = df_ml['hour'].isin([6,7,8,17,18,19,20]).astype(int)  # Horarios estudiantiles/laborales
df_ml['is_weekend'] = (df_ml['day_of_week'] >= 5).astype(int)

# Features de comportamiento de red
df_ml['connection_efficiency'] = df_ml['total_connections'] / (df_ml['total_disconnections'] + 1)
df_ml['auth_per_client'] = df_ml['total_auth'] / (df_ml['unique_clients'] + 1)
df_ml['events_per_client'] = df_ml['total_events'] / (df_ml['unique_clients'] + 1)

# 🎯 TARGET: "Riesgo de Falla Crítica"
# Combinamos: alta desconexión + alto impacto social
threshold_disconnect = df_ml['disconnection_rate'].quantile(0.7)
df_ml['target_critical'] = ((df_ml['disconnection_rate'] > threshold_disconnect) &
                           (df_ml['social_weight'] >= 1.2)).astype(int)

print(f"📊 Distribución del target (1 = Falla Crítica Social):")
print(df_ml['target_critical'].value_counts(normalize=True).round(3))

# ANÁLISIS TEMPORAL: ¿Cuándo ocurren más fallas?
